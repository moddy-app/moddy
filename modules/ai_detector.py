"""
AI Detector module — tells a channel where a posted image comes from.

Under every message carrying a PNG, JPEG or WebP image, Moddy checks the
image's **Content Credentials** (C2PA): a manifest signed by the tool or the
camera that produced the file. When the signature chains to the official C2PA
trust list (validation state ``Trusted``), the module answers the message with
what the signer declared — generated by AI, partially generated, authenticated
photograph, retouched photograph. A PNG carrying unsigned Stable Diffusion /
ComfyUI parameters gets a softer "probably generated" card.

Silence is the default: no manifest, an untrusted signer, a tampered file, a
download failure — nothing is posted. Only positive, verifiable findings speak.

**Default-enabled** (``DEFAULT_ENABLED``): runs in every server that never
touched it. A server pauses it from /config -> Manage, or turns off single
verdict kinds and ignores channels on the module screen.

The analysis itself lives in ``services/ai_detector_service.py`` (shared with
``/ai-check`` and the details button); this module only decides *whether* to
answer in a server. See docs/features/AI_DETECTOR.md.
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional

import discord

from aidetector import manifest as mf
from modules.module_manager import ModuleBase
from utils.emojis import AI_SHIELD

logger = logging.getLogger("moddy.modules.ai_detector")

#: Verdict families a server can switch on or off, in display order.
CATEGORY_AI_FULL = "ai_full"
CATEGORY_AI_PARTIAL = "ai_partial"
CATEGORY_PHOTO = "photo"
CATEGORY_UNSIGNED = "unsigned"
CATEGORIES = (CATEGORY_AI_FULL, CATEGORY_AI_PARTIAL, CATEGORY_PHOTO, CATEGORY_UNSIGNED)

#: Verdict kind -> the category that governs it.
KIND_CATEGORY = {
    mf.KIND_AI_FULL: CATEGORY_AI_FULL,
    mf.KIND_AI_PARTIAL: CATEGORY_AI_PARTIAL,
    mf.KIND_PHOTO: CATEGORY_PHOTO,
    mf.KIND_PHOTO_EDITED: CATEGORY_PHOTO,
    mf.KIND_UNSIGNED: CATEGORY_UNSIGNED,
}

# Discord caps a select at 25 values — the ignored channel list follows.
MAX_IGNORED_CHANNELS = 25

NO_MENTIONS = discord.AllowedMentions.none()


def normalize_config(config: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """Stored config -> a complete, valid one (unknown values dropped)."""
    config = dict(config or {})
    raw_categories = config.get("categories")
    if isinstance(raw_categories, list):
        categories = [c for c in CATEGORIES if c in raw_categories]
    else:
        categories = list(CATEGORIES)
    raw_channels = config.get("ignored_channel_ids") or []
    channels: List[int] = []
    if isinstance(raw_channels, list):
        for value in raw_channels:
            if str(value).isdigit() and int(value) not in channels:
                channels.append(int(value))
    normalized = {**config, "categories": categories,
                  "ignored_channel_ids": channels[:MAX_IGNORED_CHANNELS]}
    return normalized


class AiDetectorModule(ModuleBase):
    """Answers images whose origin is cryptographically attested."""

    MODULE_ID = "ai_detector"
    MODULE_NAME = "AI Detector"
    MODULE_DESCRIPTION = "Signale les images générées par IA (signatures C2PA)"
    MODULE_EMOJI = AI_SHIELD
    MODULE_ORDER = 105
    DEFAULT_ENABLED = True
    # Replies in the channel the image was posted in: the baseline (view, send,
    # history, external emojis) covers it, nothing module-specific.
    REQUIRED_BOT_PERMISSIONS: List[str] = []

    def __init__(self, bot, guild_id: int):
        super().__init__(bot, guild_id)
        self.categories: List[str] = list(CATEGORIES)
        self.ignored_channel_ids: List[int] = []

    # ----------------------------------------------------------------- #
    # Configuration
    # ----------------------------------------------------------------- #

    def get_default_config(self) -> Dict[str, Any]:
        return {"categories": list(CATEGORIES), "ignored_channel_ids": []}

    async def load_config(self, config_data: Dict[str, Any]) -> bool:
        try:
            config = normalize_config(config_data)
            self.config = config
            self.categories = config["categories"]
            self.ignored_channel_ids = config["ignored_channel_ids"]
            # Pause / resume is the generic module state (apply_state).
            self.enabled = True
            return True
        except Exception as e:  # noqa: BLE001
            logger.error(f"Error loading ai_detector config: {e}")
            return False

    async def validate_config(self, config_data: Dict[str, Any]) -> tuple[bool, Optional[str]]:
        categories = config_data.get("categories")
        if not isinstance(categories, list) or any(c not in CATEGORIES for c in categories):
            return False, "Catégories invalides"
        channels = config_data.get("ignored_channel_ids") or []
        if not isinstance(channels, list) or not all(str(c).isdigit() for c in channels):
            return False, "La liste des salons est invalide"
        if len(channels) > MAX_IGNORED_CHANNELS:
            return False, f"Maximum {MAX_IGNORED_CHANNELS} salons"
        return True, None

    # ----------------------------------------------------------------- #
    # Runtime
    # ----------------------------------------------------------------- #

    def allowed_kinds(self) -> List[str]:
        return [kind for kind, category in KIND_CATEGORY.items() if category in self.categories]

    def handles_channel(self, channel) -> bool:
        """False in an ignored channel (a thread follows its parent)."""
        ids = {getattr(channel, "id", None), getattr(channel, "parent_id", None)}
        return not (ids & set(self.ignored_channel_ids))

    async def on_message(self, message: discord.Message) -> None:
        if not self.enabled or message.author.bot or message.guild is None:
            return
        service = getattr(self.bot, "ai_detector", None)
        if service is None or not service.candidate_images(message):
            return
        if not self.categories or not self.handles_channel(message.channel):
            return
        me = message.guild.me
        if me is not None and not message.channel.permissions_for(me).send_messages:
            return

        found = await service.analyze_message(
            message, automatic=True, kinds=self.allowed_kinds())
        if found is None:
            return
        attachment, result = found

        from utils.ai_detector_views import build_verdict_view
        from utils.guild_language import guild_locale
        # Read by the whole channel: the server language.
        locale = await guild_locale(self.bot, message.guild)
        view = build_verdict_view(
            result, locale, button=(message.channel.id, message.id, attachment.id))
        if view is None:
            return
        try:
            await message.reply(view=view, mention_author=False, allowed_mentions=NO_MENTIONS)
        except discord.Forbidden:
            logger.debug(f"No permission to reply to an image in guild {self.guild_id}")
            return
        except discord.HTTPException as e:
            logger.warning(f"Could not reply to an image in guild {self.guild_id}: {e}")
            return
        self.count(result.kind)
        service.record(result.kind, "auto")
