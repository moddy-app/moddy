"""
``/ai-check`` — check an image's origin on demand (C2PA + generation metadata).

Same analysis as the ``ai_detector`` module (``services/ai_detector_service.py``),
but it always answers: with the verdict and its details when there is one, with
the reason there is none otherwise (no Content Credentials, a signer outside
the official trust list, a tampered file…).

The image comes either as an attachment or as a link to a message of this
server — Discord's five message context menus are all taken (see
``cogs/voice_transcription.py``), so the link is how a member checks an image
someone else posted. A linked message is only read when the requester can see
its channel. Ephemeral by default (``incognito``). See docs/features/AI_DETECTOR.md.
"""

from __future__ import annotations

import logging
import re
from typing import Optional

import discord
from discord import app_commands
from discord.ext import commands

from aidetector import analysis as an
from aidetector import formats
from utils.ai_detector_views import (
    NO_MENTIONS, build_check_view, render_error_card, render_loading_card,
)
from utils.i18n import i18n
from utils.incognito import add_incognito_option, get_incognito_setting

logger = logging.getLogger("moddy.ai_detector")

MESSAGE_LINK_RE = re.compile(
    r"https?://(?:(?:ptb|canary)\.)?discord(?:app)?\.com/channels/"
    r"(?P<guild_id>\d+)/(?P<channel_id>\d+)/(?P<message_id>\d+)"
)


class AiDetector(commands.Cog):
    def __init__(self, bot):
        self.bot = bot

    @app_commands.command(name="ai-check",
                          description="Check whether an image was generated by AI")
    @app_commands.allowed_installs(guilds=True, users=True)
    @app_commands.allowed_contexts(guilds=True, dms=True, private_channels=True)
    @app_commands.describe(
        image="The image to check (PNG, JPEG or WebP)",
        message="Link to a message of this server containing the image",
        incognito="Make response visible only to you",
    )
    @add_incognito_option()
    async def ai_check(self, interaction: discord.Interaction,
                       image: Optional[discord.Attachment] = None,
                       message: Optional[str] = None,
                       incognito: Optional[bool] = None):
        locale = i18n.get_user_locale(interaction)
        ephemeral = get_incognito_setting(interaction)
        service = getattr(self.bot, "ai_detector", None)
        if service is None:
            await interaction.response.send_message(
                view=render_error_card("unavailable", locale), ephemeral=True)
            return

        if image is None and not message:
            await interaction.response.send_message(
                view=render_error_card("no_image", locale), ephemeral=True)
            return
        if image is not None and formats.declared_mime(image.filename, image.content_type) is None:
            await interaction.response.send_message(
                view=render_error_card(an.REASON_UNSUPPORTED, locale), ephemeral=True)
            return

        await interaction.response.send_message(view=render_loading_card(locale),
                                                ephemeral=ephemeral)

        if image is not None:
            result = await service.analyze_attachment(image)
        else:
            target, error = await self._message_from_link(interaction, message)
            if target is None:
                await interaction.edit_original_response(view=render_error_card(error, locale))
                return
            # Several images: the strongest verdict; none: why the first has none.
            found = await service.analyze_message(target)
            result = (found[1] if found is not None
                      else await service.analyze_attachment(service.candidate_images(target)[0]))
        if result.reason in (an.REASON_TOO_LARGE, an.REASON_DOWNLOAD_FAILED):
            await interaction.edit_original_response(
                view=render_error_card(result.reason, locale))
            return

        service.record(result.kind, "command")
        await interaction.edit_original_response(
            view=build_check_view(result, locale), allowed_mentions=NO_MENTIONS)

    async def _message_from_link(self, interaction: discord.Interaction,
                                 link: Optional[str]):
        """``(message, None)`` — a message with at least one image — or
        ``(None, error_reason)``.

        Only messages of the server the command runs in, in a channel the
        requester can read: the command must never become a way to look into
        a channel one cannot see.
        """
        match = MESSAGE_LINK_RE.search(link or "")
        if match is None:
            return None, "bad_link"
        guild = interaction.guild
        if guild is None or int(match["guild_id"]) != guild.id:
            return None, "other_server"

        channel = guild.get_channel_or_thread(int(match["channel_id"]))
        member = interaction.user if isinstance(interaction.user, discord.Member) else None
        if channel is None or member is None:
            return None, "gone"
        perms = channel.permissions_for(member)
        if not (perms.view_channel and perms.read_message_history):
            return None, "gone"
        try:
            target = await channel.fetch_message(int(match["message_id"]))
        except (discord.NotFound, discord.Forbidden, discord.HTTPException):
            return None, "gone"

        if not self.bot.ai_detector.candidate_images(target):
            return None, "no_image"
        return target, None


async def setup(bot):
    await bot.add_cog(AiDetector(bot))
